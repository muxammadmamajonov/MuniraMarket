import { defineConfig, globalIgnores } from 'eslint/config';
import nextVitals from 'eslint-config-next/core-web-vitals';
import nextTs from 'eslint-config-next/typescript';

const USE_CUSTOM = 'use the custom component from src/components/ui instead';
const BANNED_INPUT_TYPES = 'date|time|datetime-local|month|week|color|range|file|search';
const BANNED_DIALOGS = 'alert|confirm|prompt';

/**
 * The storefront shows no browser/OS-default controls: native pickers, selects, dialogs and the
 * built-in alert/confirm/prompt are replaced by custom, accessible components.
 */
const noNativeControls = [
  {
    selector: 'JSXOpeningElement[name.type="JSXIdentifier"][name.name="select"]',
    message: `Native <select> is not allowed: use <ListboxSelect> (${USE_CUSTOM}).`,
  },
  {
    selector: 'JSXOpeningElement[name.type="JSXIdentifier"][name.name="option"]',
    message: `Native <option> is not allowed: pass options to <ListboxSelect> (${USE_CUSTOM}).`,
  },
  {
    selector: 'JSXOpeningElement[name.type="JSXIdentifier"][name.name="datalist"]',
    message: `Native <datalist> is not allowed: ${USE_CUSTOM}.`,
  },
  {
    selector: 'JSXOpeningElement[name.type="JSXIdentifier"][name.name="dialog"]',
    message: `Native <dialog> is not allowed: use <BottomSheet> or another custom dialog (${USE_CUSTOM}).`,
  },
  {
    selector: `JSXOpeningElement[name.name="input"] > JSXAttribute[name.name="type"][value.type="Literal"][value.value=/^(${BANNED_INPUT_TYPES})$/]`,
    message: `This <input type> renders a browser-default control: ${USE_CUSTOM}.`,
  },
  {
    selector: `JSXOpeningElement[name.name="input"] > JSXAttribute[name.name="type"] > JSXExpressionContainer > Literal[value=/^(${BANNED_INPUT_TYPES})$/]`,
    message: `This <input type> renders a browser-default control: ${USE_CUSTOM}.`,
  },
  {
    selector: `CallExpression[callee.type="Identifier"][callee.name=/^(${BANNED_DIALOGS})$/]`,
    message: `alert/confirm/prompt show a browser dialog: use a custom dialog or <BottomSheet> (${USE_CUSTOM}).`,
  },
  {
    selector: `CallExpression[callee.type="MemberExpression"][callee.object.name=/^(window|globalThis)$/][callee.property.name=/^(${BANNED_DIALOGS})$/]`,
    message: `window.alert/confirm/prompt show a browser dialog: use a custom dialog or <BottomSheet> (${USE_CUSTOM}).`,
  },
];

export default defineConfig([
  ...nextVitals,
  ...nextTs,
  {
    files: ['src/**/*.{ts,tsx}'],
    ignores: ['**/*.test.{ts,tsx}'],
    rules: { 'no-restricted-syntax': ['error', ...noNativeControls] },
  },
  // playwright-report/ and test-results/ are generated by `pnpm test:e2e` (minified HTML report).
  globalIgnores([
    '.next/**',
    'out/**',
    'build/**',
    'coverage/**',
    'playwright-report/**',
    'test-results/**',
    'next-env.d.ts',
    // Cloudflare Workers (vinext) build output and generated binding types.
    'dist/**',
    '.cloudflare/**',
    '.vinext/**',
  ]),
]);
